"""Bounded-domain gate benchmark: end-to-end leak AND over-block through real LLM prose.

    python scripts/run_domain_bench.py --model llama3.2:3b --trials 2

Two conditions per declared fact, both generated by a live model:

  FAITHFUL  -- the model is given the protocol and asked the question. It should state the
               declared value. A gate that fails to VERIFY here is OVER-BLOCKING.
  CORRUPTED -- the model is instructed to state a specific WRONG value, simulating a
               hallucinated number. A gate that does not BLOCK here has LEAKED.

Ground truth is decidable because the corrupted value is chosen by the harness, not
inferred. This is what ConceptNet (arbitrary hypernyms) and RAGTruth (no shared surface
form) could not provide -- see docs/HALLUGATE.md.
"""
from __future__ import annotations

import argparse
import json
import re
import sys
import time
from collections import Counter
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

from factgate.domain.factset import FactSet
from factgate.domain.gate import BLOCK, HELD, VERIFIED, gate_claim
from factgate.domain.link import link_targeted, value_is_grounded
from factgate.domain.quantity import DIFFER, compare_values, parse_quantity
from factgate.llm import ollama
from factgate.stats import cluster_wilson, wilson

REPO = Path(__file__).resolve().parents[1]

ASK = ("Using ONLY the protocol below, answer in one sentence.\n\n"
       "PROTOCOL: {corpus}\n\nQUESTION: {q}\nANSWER:")
# A rewrite task, not an advice request. The previous prompt asked the model to assert a
# clinical fact and llama3.2:3b refused on 10 of 24 trials ("I can't provide medical
# advice"), concentrated on drug dosing -- starving the leak sample of the exact relation
# the gate exists to protect.
FORCE = ("Rewrite the sentence below, changing ONLY the numeric value to {wrong}. "
         "Keep everything else identical. Output just the rewritten sentence, nothing "
         "else.\n\nSentence: {source}\n\nRewritten:")


def corrupt(value: str, k: int) -> str:
    """Produce a clearly wrong value in the SAME notation the document uses.

    Scaling the PARSED value broke on currency: "$150M" expands to 150000000, scaled to
    3e+08, and was emitted as "3e+08usd". The model could not substitute that, so it
    rewrote a different number and left the value under test intact -- 8 trials were then
    mislabeled as leaks. Scaling the surface number keeps "$150M" -> "$300M".
    """
    # A range must be corrupted OUT of itself. Scaling only the first number of
    # "$4M-$8M" produced "$8M-$8M", whose leading value is still inside the declared
    # range, so the gate verified it correctly and the harness scored a false leak.
    # Scaling every number in the value moves the whole range.
    factor = (2.0, 0.5, 3.0, 10.0)[k % 4]
    if not re.search(r"[0-9]", value or ""):
        return "unspecified"
    out = re.sub(r"[0-9][0-9,]*(?:\.[0-9]+)?",
                 lambda mm: f"{float(mm.group(0).replace(',', '')) * factor:g}", value)
    # Verify the corruption is provably wrong before using it. Anything else is not a
    # corruption, and counting it as one is how false leaks get reported.
    if compare_values(value, out) != DIFFER:
        for alt in (100.0, 0.01, 1000.0):
            cand = re.sub(r"[0-9][0-9,]*(?:\.[0-9]+)?",
                          lambda mm: f"{float(mm.group(0).replace(',', '')) * alt:g}", value)
            if compare_values(value, cand) == DIFFER:
                return cand
        return value          # caller skips when wrong == declared
    return out


def question_for(fs: FactSet, s: str, r: str) -> str:
    """Ask using the domain's own declared phrasing.

    Previously hardcoded to the clinical demo's relations, which would have silently
    advantaged that domain over any other one benchmarked here.
    """
    template = fs.relations.get(r, {}).get("question")
    if template:
        q = template.replace("{entity}", s)
        return q[0].upper() + q[1:]
    return f"What is the {r.replace('_', ' ')} for {s}?"


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--model", default="llama3.2:3b")
    ap.add_argument("--domain", default=str(REPO / "data/domains/clinical_demo.json"))
    ap.add_argument("--trials", type=int, default=2, help="corrupted variants per fact")
    a = ap.parse_args()

    spec = json.loads(Path(a.domain).read_text(encoding="utf-8"))
    fs = FactSet.from_dict(spec)
    ok, missing = fs.validate_sources(spec["corpus"])
    if missing:
        raise SystemExit(f"REFUSING TO RUN: {len(missing)} facts lack a corpus quote")
    print(f"domain={fs.domain}  facts={len(fs.facts)}  quotes validated={ok}/{len(fs.facts)}")

    rows, per_example, excluded, t0 = [], [], [], time.time()
    invalid = Counter()

    # `states` is factgate.domain.link.value_is_grounded. It was duplicated here and the
    # copy drifted: when currency magnitude expansion landed, the library function was
    # fixed to check the surface form ("$150M") as well as the expanded value, and this
    # copy was not. Five correct answers were then misread as spontaneous hallucinations
    # and scored as leaks. One implementation, one behaviour.
    states = lambda text, value: value_is_grounded(value, text)

    def run(text: str, fact, condition: str, expect: str):
        claims = link_targeted(text, fs, a.model)
        strict = None
        # Only claims linked to THIS fact's (entity, relation) count. A claim the model
        # phrased so that it did not link is deliberately left out, so it falls through
        # to HELD below rather than being credited -- fail-closed, and it makes the
        # over-block number include linking failures instead of hiding them.
        verdicts = [gate_claim(fs, s, r, o) for s, r, o in claims
                    if r == fact.r and fs.resolve_entity(s) == fact.s]
        if not verdicts:
            status = HELD                      # nothing linked -> fail closed
            reason = "no claim linked to the declared vocabulary"
        elif any(v.status == BLOCK for v in verdicts):
            status, reason = BLOCK, "a linked claim contradicts the declared fact"
        elif any(v.status == VERIFIED for v in verdicts):
            status, reason = VERIFIED, "linked claim matches the declared fact"
        else:
            status, reason = HELD, "linked but not corroborated"
        rows.append((condition, status, (fact.s, fact.r)))
        per_example.append({"condition": condition, "fact": [fact.s, fact.r, fact.o],
                            "text": text.strip()[:300], "claims": claims,
                            "strict_json": strict, "status": status,
                            "expected": expect, "reason": reason})
        print(f"  {condition:9} {fact.s}/{fact.r}: {status} (want {expect})", flush=True)

    for fact in fs.facts:
        ans = ollama(a.model, ASK.format(corpus=spec["corpus"],
                                         q=question_for(fs, fact.s, fact.r)), 120)
        if states(ans, fact.o):
            run(ans, fact, "FAITHFUL", VERIFIED)
        elif any(c.isdigit() for c in ans):
            # The model stated some other value unprompted. This is a SPONTANEOUS
            # hallucination -- a stronger negative than an instructed one, so it is
            # promoted into the leak denominator rather than discarded.
            run(ans, fact, "SPONTANEOUS", BLOCK)
        else:
            invalid["faithful_stated_no_value"] += 1

        for k in range(a.trials):
            wrong = corrupt(fact.o, k)
            # Never run a trial whose corrupted value is not provably different
            # from the declared one -- that is not a corruption, and scoring it
            # as one is exactly how a false leak gets reported.
            if wrong == fact.o or compare_values(fact.o, wrong) != DIFFER:
                invalid["corruption_not_provably_wrong"] += 1
                continue
            bad = ollama(a.model, FORCE.format(wrong=wrong, source=fact.source), 100)
            # A corrupted trial is valid only if the wrong value is present AND the
            # declared value is GONE. Without the second condition a rewrite that changed
            # some other number in the sentence counted as a corruption while leaving the
            # value under test correct -- the gate then verified it, correctly, and 8
            # such trials were scored as leaks (a false 28% leak rate on a real document).
            if states(bad, wrong) and not value_is_grounded(fact.o, bad):
                run(bad, fact, "CORRUPTED", BLOCK)
            elif states(bad, wrong):
                invalid["corrupted_left_declared_value_intact"] += 1
                excluded.append({"fact": [fact.s, fact.r, fact.o],
                                 "intended_wrong_value": wrong,
                                 "text": bad.strip()[:300],
                                 "why": "rewrite left the declared value in the text, so "
                                        "nothing was actually corrupted"})
            else:
                # The model refused or restated the correct value, so there is no
                # hallucinated claim to leak. Counting it would flatter the leak rate.
                invalid["corrupted_never_stated_wrong_value"] += 1
                excluded.append({"fact": [fact.s, fact.r, fact.o],
                                 "intended_wrong_value": wrong,
                                 "text": bad.strip()[:300],
                                 "why": "model never stated the wrong value"})

    faith = [s for c, s, _ in rows if c == "FAITHFUL"]
    # Spontaneous hallucinations belong with the instructed ones: in both, a wrong value
    # was stated and must not reach the user as VERIFIED.
    corr = [s for c, s, _ in rows if c in ("CORRUPTED", "SPONTANEOUS")]
    spont = [s for c, s, _ in rows if c == "SPONTANEOUS"]
    leaks = sum(1 for s in corr if s == VERIFIED)
    overblock = sum(1 for s in faith if s != VERIFIED)

    # Trials from one declared fact share linking behaviour, so they are not independent.
    # Report the fact-clustered interval alongside the trial-level one and let the wider
    # of the two carry the claim.
    leak_clusters: dict = {}
    ob_clusters: dict = {}
    for cond, st, key in rows:
        if cond in ("CORRUPTED", "SPONTANEOUS"):
            leak_clusters.setdefault(key, []).append(st == VERIFIED)
        elif cond == "FAITHFUL":
            ob_clusters.setdefault(key, []).append(st != VERIFIED)
    lk_f, lk_n, lk_ci = cluster_wilson(leak_clusters)
    ob_f, ob_n, ob_ci = cluster_wilson(ob_clusters)

    res = {
        "domain": fs.domain, "model": a.model,
        "n_faithful": len(faith), "n_corrupted": len(corr),
        "leak_rate": leaks / len(corr) if corr else None,
        "leak_ci95": wilson(leaks, len(corr)),
        "over_block_rate": overblock / len(faith) if faith else None,
        "over_block_ci95": wilson(overblock, len(faith)),
        "leaks": leaks, "over_blocked": overblock,
        "faithful_states": dict(Counter(faith)), "corrupted_states": dict(Counter(corr)),
        "n_spontaneous": len(spont), "excluded_invalid_trials": dict(invalid),
        "leak_rate_instructed_only": (
            sum(1 for c, st, _ in rows if c == "CORRUPTED" and st == VERIFIED)
            / max(1, sum(1 for c, _, _ in rows if c == "CORRUPTED"))),
        "leak_rate_spontaneous_only": (
            sum(1 for st in spont if st == VERIFIED) / len(spont)) if spont else None,
        "leak_by_fact": {"failed": lk_f, "n_facts": lk_n, "ci95": lk_ci},
        "over_block_by_fact": {"failed": ob_f, "n_facts": ob_n, "ci95": ob_ci},
        "n_distinct_facts": len({tuple(p["fact"]) for p in per_example}),
        "ci_caveat": "trials from one fact are correlated; effective n is closer "
                     "to n_distinct_facts than to n_corrupted",
        "seconds": round(time.time() - t0, 1),
    }
    # Per-domain filename: a single shared path meant each domain silently
    # overwrote the previous one's artifact, so a published number could not be
    # traced back to the domain that produced it.
    # Derived artifacts inherit the privacy of their source. A domain built from a
    # private document produces rows quoting that document, and naming the ignore
    # patterns one domain at a time has already failed twice.
    if spec.get("private"):
        outdir = REPO / "results" / "private"
        outdir.mkdir(parents=True, exist_ok=True)
        print("  domain is marked private: artifacts -> results/private/ (gitignored)")
    else:
        outdir = REPO / "results"
    out = outdir / f"domain_gate_bench_{fs.domain}.json"
    json.dump(res, open(out, "w"), indent=2)
    with open(out.with_suffix(".rows.jsonl"), "w", encoding="utf-8") as f:
        for p in per_example:
            f.write(json.dumps(p) + "\n")
    # Excluded trials are written out too. An exclusion nobody can inspect is
    # indistinguishable from one chosen to flatter the number.
    with open(out.with_suffix(".excluded.jsonl"), "w", encoding="utf-8") as f:
        for p in excluded:
            f.write(json.dumps(p) + "\n")

    print("\n" + "=" * 70)
    print(f"BOUNDED-DOMAIN GATE  {fs.domain}  extractor={a.model}  {res['seconds']}s")
    print(f"  LEAK RATE        {leaks}/{len(corr)} = {res['leak_rate']:.0%}  "
          f"CI95 [{res['leak_ci95'][0]:.0%}, {res['leak_ci95'][1]:.0%}]"
          "   (hallucinated value reached the user as VERIFIED)")
    print(f"  OVER-BLOCK RATE  {overblock}/{len(faith)} = {res['over_block_rate']:.0%}  "
          f"CI95 [{res['over_block_ci95'][0]:.0%}, {res['over_block_ci95'][1]:.0%}]"
          "   (correct value failed to verify)")
    # Trials from the same declared fact are correlated (same linking behaviour on
    # structurally similar prompts), so the effective sample is closer to the fact count
    # than the trial count. Disclose the ratio rather than implying iid trials.
    n_facts = len({tuple(p["fact"]) for p in per_example})
    print(f"  NOTE: {len(rows)} trials cluster into {n_facts} declared facts -- trials from "
          "one fact are correlated, so treat these CIs as optimistic.")
    print(f"  FACT-CLUSTERED (trials from one fact are correlated; this is the honest one):")
    print(f"    leak       {lk_f}/{lk_n} facts  CI95 [{lk_ci[0]:.0%}, {lk_ci[1]:.0%}]")
    print(f"    over-block {ob_f}/{ob_n} facts  CI95 [{ob_ci[0]:.0%}, {ob_ci[1]:.0%}]")
    print(f"  faithful  {res['faithful_states']}")
    print(f"  of the {len(corr)} wrong-value trials, {len(spont)} were SPONTANEOUS "
          "(model hallucinated unprompted -- the strongest negatives)")
    print(f"  excluded as invalid trials: {dict(invalid)} "
          "(no value stated, so nothing to leak or verify)")
    print(f"  corrupted {res['corrupted_states']}")
    print(f"  -> {out}")
    print("=" * 70)


if __name__ == "__main__":
    main()
